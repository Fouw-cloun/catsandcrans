using UnityEngine;

/// <summary>
/// ПИЛЯЩИЙ ИНСТРУМЕНТ — ножовка, нож, будущая пила.
///
/// Нужен, чтобы SawFoodProcessor не знал, какой именно инструмент к нему
/// прикручен: появится нож — реализует этот же интерфейс, и нарезка заработает
/// на нём без правок. Ровно та же роль, что у ISpinningTool для болгарки.
/// </summary>
public interface ISawTool
{
    /// <summary>Игрок держит ЛКМ — пилит прямо сейчас.</summary>
    bool IsSawing { get; }

    /// <summary>Полотно. От него считается подача вперёд и рисуются крошки.</summary>
    Transform Blade { get; }

    /// <summary>
    /// Камера того, кто держит инструмент. Берётся через руку, поэтому это
    /// гарантированно нужный игрок — в отличие от поиска по сцене, который
    /// легко цепляет чужую или служебную камеру.
    /// </summary>
    Transform AimOrigin { get; }
}

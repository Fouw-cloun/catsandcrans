/// <summary>
/// Куда дует пылесос. ВКЛЮЧЕНИЕ сюда не входит: им ведает кнопка компрессора
/// на корпусе базы, а дуло только выбирает направление.
/// </summary>
public enum VacuumMode : byte
{
    Suck,     // всасывает
    Blow      // выплёвывает по очереди
}

/// <summary>Как предмет ведёт себя под всасыванием.</summary>
public enum SuckableSize : byte
{
    /// <summary>Мелочь: втягивается внутрь и лежит в баке.</summary>
    Small,

    /// <summary>Крупное: присасывается к дулу и висит на нём, внутрь не лезет.</summary>
    Large,

    /// <summary>Не всасывается вовсе.</summary>
    None
}

using UnityEngine;

/// <summary>
/// ВРАЩАЮЩИЙСЯ ИНСТРУМЕНТ — болгарка, шлифмашинка, будущая тёрка.
///
/// Нужен, чтобы обработчик еды (GrinderFoodProcessor) не знал, какой именно
/// инструмент к нему прикручен. Появится шлифмашинка — реализует этот же
/// интерфейс, и чистка заработает на ней без единой правки.
///
/// Реализуется тремя строчками, см. комментарий в GrinderFoodProcessor.
/// </summary>
public interface ISpinningTool
{
    /// <summary>Работает прямо сейчас: крутится И оснастка на месте.</summary>
    bool IsActive { get; }

    /// <summary>Раскрутка 0..1. Идёт в качество обработки: на полных оборотах
    /// чистится ровнее, чем на подвисающих.</summary>
    float Power01 { get; }

    /// <summary>Рабочая точка — центр диска. Вокруг неё ищется еда.</summary>
    Transform WorkPoint { get; }
}

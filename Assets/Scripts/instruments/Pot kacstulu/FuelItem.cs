using UnityEngine;

/// <summary>Что это за топливо. Порядок важен: чем ниже, тем труднее поджечь и
/// тем дольше горит.</summary>
public enum FuelKind : byte
{
    /// <summary>Растопка: щепа, стружка, бумага. Вспыхивает мгновенно, сгорает
    /// за секунды, жара почти не даёт.</summary>
    Tinder = 0,

    /// <summary>Хворост, мелкие палки. Загорается от растопки, держит огонь,
    /// пока не займутся дрова.</summary>
    Kindling = 1,

    /// <summary>Дрова — наши четвертинки. Сами по себе не загораются, зато
    /// дают основной жар и превращаются в угли.</summary>
    Firewood = 2,

    /// <summary>Уголь. В костёр не кидается, получается сам из дров.</summary>
    Coal = 3
}

/// <summary>
/// ТОПЛИВО. Вешается на префаб всего, что горит: четвертинки бревна, вязанки
/// хвороста, ящика со стружкой.
///
/// ═══ ПОЧЕМУ ДВА ЧИСЛА, А НЕ ОДНО ═══
///
/// Топливо описывается ЖАРОМ и РАЗГОРАЕМОСТЬЮ, и это разные вещи. Хворост
/// вспыхивает от искры, но прогорает за полминуты. Четвертинка горит двадцать
/// минут, но от горелки не займётся никогда — её надо поджигать уже горящим
/// костром.
///
/// Одним числом «сколько горит» этого не выразить, а без разделения вся
/// закладка костра вырождается в «накидай побольше». С двумя числами появляется
/// настоящая задача: снизу растопка, на неё хворост, сверху дрова — и только в
/// таком порядке костёр вообще заведётся.
///
/// ═══ МАССУ БЕРЁМ У CuttableLog, ЕСЛИ ОН ЕСТЬ ═══
///
/// Четвертинка уже носит свой вес — распил честно делит килограммы от бревна
/// вниз по уровням. Дублировать это число здесь значило бы завести второй
/// источник правды, который рано или поздно разойдётся с первым.
/// </summary>
public class FuelItem : MonoBehaviour
{
    [Header("Что это")]
    [SerializeField] private FuelKind _kind = FuelKind.Firewood;

    [Tooltip("Вес, кг. ИГНОРИРУЕТСЯ, если на объекте есть CuttableLog — там вес " +
             "уже посчитан распилом и является единственной правдой.")]
    [Min(0.1f)][SerializeField] private float _massKg = 10f;

    [Header("Горение")]
    [Tooltip("Сколько жара даёт килограмм. Условные единицы — важны только " +
             "соотношения.\n\n" +
             "Растопка ~20, хворост ~60, дрова ~140.")]
    [Min(1f)][SerializeField] private float _heatPerKg = 140f;

    [Tooltip("КАК ЛЕГКО ЗАНИМАЕТСЯ, 0..1.\n\n" +
             "1 — вспыхивает от горелки сразу. 0 — само не загорится никогда, " +
             "нужен уже горящий костёр под ним.\n\n" +
             "Растопка 1, хворост 0.6, дрова 0.05.")]
    [Range(0f, 1f)][SerializeField] private float _ignitability = 0.05f;

    [Tooltip("Какая доля массы остаётся углями, а не улетает дымом. Уголь потом " +
             "горит долго и ровно.\n\n" +
             "У дров ~0.25, у хвороста ~0.05, у растопки 0.")]
    [Range(0f, 0.6f)][SerializeField] private float _coalYield = 0.25f;

    private CuttableLog _log;

    private void Awake() => _log = GetComponent<CuttableLog>();

    public FuelKind Kind => _kind;

    /// <summary>Вес. У четвертинки берётся из распила, у всего прочего — своё.</summary>
    public float MassKg => _log != null ? _log.MassKg : _massKg;

    public float HeatPerKg => _heatPerKg;
    public float Ignitability => _ignitability;
    public float CoalYield => _coalYield;

    /// <summary>Сколько жара в этой штуке целиком.</summary>
    public float TotalHeat => MassKg * _heatPerKg;
}

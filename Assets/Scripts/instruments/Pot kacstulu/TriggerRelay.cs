using System;
using UnityEngine;

/// <summary>
/// РЕТРАНСЛЯТОР ТРИГГЕРА. Вешается автоматически, руками добавлять не надо.
///
/// ═══ ЗАЧЕМ ОН ВООБЩЕ НУЖЕН ═══
///
/// Unity шлёт OnTriggerEnter ТОЛЬКО на тот GameObject, где висит сам коллайдер
/// (и на объект его Rigidbody, если он есть). Вверх по иерархии событие НЕ
/// ВСПЛЫВАЕТ — в отличие от, скажем, UI-событий, где всплытие есть, и это
/// сбивает с толку.
///
/// А у нас триггеры почти всегда дочерние: JumpZone у мехов, IntakeZone у
/// костра. Скрипт при этом сидит на родителе, потому что ему нужны и другие
/// части (меш шины, точка огня, поленница). В итоге событие уходит в дочерний
/// объект, где его никто не слушает, и до скрипта не доходит.
///
/// Проявляется это ХУЖЕ ВСЕГО: никаких ошибок, никаких предупреждений, просто
/// молча ничего не происходит. Ни воздуха, ни анимации, ни приёма топлива.
///
/// ═══ ПОЧЕМУ НЕ ПРОСТО ПОВЕСИТЬ RIGIDBODY НА КОРЕНЬ ═══
///
/// Это второй способ решения: с Rigidbody на родителе событие пришло бы и туда.
/// Но Rigidbody на статичной костровой станции — это лишнее физическое тело,
/// которое надо делать кинематическим, следить чтобы оно не спало, и которое
/// однажды кто-нибудь сделает динамическим и уронит всю станцию.
///
/// Ретранслятор дешевле и ничего не меняет в физике.
///
/// ═══ ПОЧЕМУ ДОБАВЛЯЕТСЯ КОДОМ, А НЕ РУКАМИ ═══
///
/// Забыть повесить его на один из триггеров — ровно тот же молчаливый отказ,
/// от которого мы избавляемся. Скрипты, которым он нужен, ставят его себе сами
/// в Awake через AddComponent.
/// </summary>
[DisallowMultipleComponent]
public class TriggerRelay : MonoBehaviour
{
    public event Action<Collider> Entered;
    public event Action<Collider> Exited;

    private void OnTriggerEnter(Collider other) => Entered?.Invoke(other);
    private void OnTriggerExit(Collider other) => Exited?.Invoke(other);

    /// <summary>Поставить ретранслятор на объект коллайдера (или найти уже
    /// стоящий) и подписаться. Возвращает null, если коллайдера нет — звонящий
    /// сам решает, ошибка это или нет.</summary>
    public static TriggerRelay Attach(Collider target)
    {
        if (target == null) return null;

        TriggerRelay relay = target.GetComponent<TriggerRelay>();
        if (relay == null) relay = target.gameObject.AddComponent<TriggerRelay>();
        return relay;
    }
}

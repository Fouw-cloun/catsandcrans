using FishNet.Object;
using UnityEngine;

/// <summary>
/// РАСПИЛИВАЕМЫЙ ОБЪЕКТ — картошка, бревно, палено.
///
/// Появился, когда пилить понадобилось не только еду. ChainsawFoodProcessor
/// раньше знал про SliceableFood напрямую, а бревно едой не является: у него
/// нет ни FoodItem, ни ингредиента, ни вкуса. Второй процессор рядом с первым
/// поставить нельзя — оба тянули бы инструмент вперёд и оба рисовали бы щепу,
/// перебивая друг друга. Значит развязка идёт здесь.
///
/// Та же роль, что у ISawTool с другой стороны: инструмент не знает, что режет,
/// цель не знает, чем её режут.
/// </summary>
public interface ICuttable
{
    /// <summary>Сетевой объект цели — по нему инструмент шлёт серверу, что резать.</summary>
    NetworkObject NetworkObject { get; }

    /// <summary>Есть ли ещё что отпиливать.</summary>
    bool CanCut { get; }

    /// <summary>
    /// Своё время выдержки, секунд. НОЛЬ И МЕНЬШЕ — взять общее с инструмента.
    ///
    /// Нужно, потому что перепилить бревно и расколоть палено на четвертинки —
    /// работа очень разного объёма. Держать это число на инструменте нельзя:
    /// пила одна, а целей много.
    /// </summary>
    float SecondsPerCut { get; }

    /// <summary>Глушить ли физику цели на время распила. Бревно в двести кило
    /// от касания пилой уезжает, картошку же держит рука игрока — поэтому
    /// решает цель, а не инструмент.</summary>
    bool ClampWhileCutting { get; }

    /// <summary>Строка для отладочного HUD: «палено 3 из 5», «кусков 2».</summary>
    string CutLabel { get; }

    /// <summary>Цвет крошек. Прозрачный (a &lt; 0.01) — инструмент возьмёт свой.</summary>
    Color CrumbColor { get; }

    /// <summary>Где сейчас идёт пропил: туда подаётся полотно и летит щепа.</summary>
    Vector3 CutPoint();

    /// <summary>Отпилить одну часть. Только на сервере.</summary>
    void ServerCutOne(ProcessDef cutProcess, float quality01);

    /// <summary>Зажать цель, чтобы не убегала из-под пилы.</summary>
    void ServerSetClamped(bool value);
}

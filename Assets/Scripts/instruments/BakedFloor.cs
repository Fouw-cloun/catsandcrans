using UnityEngine;

/// <summary>
/// МЕТКА ЗАПЕЧЁННОГО ЭТАЖА.
///
/// Держит связь с исходником, из которого этаж собран, и список того, что при
/// запекании было спрятано. Без неё запекание было бы дорогой в один конец:
/// исходные модули остались бы выключенными навсегда, и поправить одну балку
/// стало бы невозможно.
///
/// Компонент рантаймовый нарочно, хотя нужен только редактору: положи его в
/// редакторную сборку — и запечённый этаж на сцене начнёт ссылаться на тип,
/// которого в билде нет. Сцена откроется со сломанным компонентом, а связь с
/// исходником потеряется.
///
/// В игре он ничего не делает и ничего не стоит.
/// </summary>
[AddComponentMenu("CatCooks/Стройка/Baked Floor")]
[DisallowMultipleComponent]
public class BakedFloor : MonoBehaviour
{
    [Tooltip("Откуда запечён. По этой ссылке работает «Восстановить».")]
    public Transform source;

    [Tooltip("Рендереры исходника, выключенные при запекании. Именно " +
             "выключенные, а не удалённые: на тех же объектах висят " +
             "коллайдеры, и снос геометрии унёс бы и их.")]
    public Renderer[] hidden;

    [Header("Что вышло")]
    public int sections;
    public int meshes;
    public int sourceRenderers;
    public int vertices;

    [Tooltip("Куда сохранены меши. Удалять папку вручную не надо — это " +
             "делает «Восстановить».")]
    public string assetFolder;
}

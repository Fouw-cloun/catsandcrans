using System;
using System.Collections.Generic;
using UnityEngine;

namespace CatCooks.Food
{
    /// <summary>Одно требование рецепта: что, в каком состоянии и сколько.</summary>
    [Serializable]
    public struct FoodNeed
    {
        public ProductDef Product;

        [Tooltip("В каком состоянии продукт должен попасть в блюдо.\n\n" +
                 "None = состояние неважно, годится любое. Так помечают воду " +
                 "и специи: их состояние на результат не влияет.")]
        public FoodState State;

        [Tooltip("Сколько порций. Количество, а не граммы — риски на таре " +
                 "показывают ровно это число.")]
        public int Count;
    }

    /// <summary>
    /// РЕЦЕПТ. Один класс и для блюд, и для полуфабрикатов.
    ///
    /// ═══ ПОЧЕМУ ОДИН, А НЕ ДВА ═══
    ///
    /// Разница между «борщом» и «бульоном» только в поле Result: борщ уходит на
    /// тарелку и оценивается, бульон возвращается в мир продуктом и становится
    /// ингредиентом для борща. Всё остальное — требования, тара, процесс —
    /// устроено одинаково.
    ///
    /// Отсюда глубина берётся сама собой: чтобы сварить борщ, нужен бульон;
    /// чтобы сварить бульон, нужны кости и вода. Игрок не читает дерево крафта,
    /// он просто обнаруживает, что для наполеона надо сперва сделать тесто.
    ///
    /// ═══ ОПАСНОСТЬ ═══
    ///
    /// Рекурсия. Если рецепт A требует продукт из рецепта B, а B требует продукт
    /// из A — подсказки зациклятся. Проверка на циклы есть в редакторском меню,
    /// гоняй её после каждой правки рецептов.
    /// </summary>
    [CreateAssetMenu(menuName = "CatCooks/Рецепт", fileName = "Recipe_")]
    public class FoodRecipeDef : ScriptableObject
    {
        [Header("Что это")]
        public string Title = "Бульон";

        [TextArea(2, 3)]
        public string Note = "";

        [Header("Требования")]
        [Tooltip("Из чего готовится. Порядок значения не имеет — подбор " +
                 "сравнивает множества, а не последовательности.")]
        public List<FoodNeed> Needs = new List<FoodNeed>();

        [Header("Как готовится")]
        [Tooltip("Основной процесс. По нему подбирается тара: варка — котёл, " +
                 "запекание — духовка.")]
        public FoodProcess Process = FoodProcess.Boil;

        [Tooltip("Сколько секунд идёт готовка целиком")]
        public float Seconds = 30f;

        [Header("Что получается")]
        [Tooltip("ПУСТО = это блюдо. Уходит на тарелку, оценивается, даёт бафф котам.\n\n" +
                 "ЗАПОЛНЕНО = это полуфабрикат. Результат возвращается в мир " +
                 "продуктом и может стать ингредиентом другого рецепта.")]
        public ProductDef ResultProduct;

        [Tooltip("Сколько порций результата выходит. Обычно столько же, " +
                 "сколько заложили, но фарш даёт меньше, а тесто больше.")]
        public int ResultCount = 1;

        /// <summary>Полуфабрикат это или блюдо. Единственное, что их различает.</summary>
        public bool IsSubRecipe => ResultProduct != null;

        /// <summary>Сколько всего порций требуется. Нужно для оценки «состав».</summary>
        public int TotalNeeded
        {
            get
            {
                int n = 0;
                for (int i = 0; i < Needs.Count; i++)
                {
                    int c = Needs[i].Count;
                    n += c < 1 ? 1 : c;
                }
                return n;
            }
        }
    }
}

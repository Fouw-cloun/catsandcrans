using UnityEngine;

namespace CatCooks.Food
{
    /// <summary>
    /// ЧТО ТАРА ДЕЛАЕТ С ТЕМ, ЧТО В НЕЁ ПОПАЛО.
    /// Это не «какая посуда», а «как ведёт себя содержимое».
    /// </summary>
    public enum CookwareKind : byte
    {
        /// <summary>Котёл: продукт растворяется в общей массе. Кастрюля, казан.
        /// Отдельных морковок в супе не видно, но список внутри сохраняется.</summary>
        Pot = 0,

        /// <summary>Плоская: куски лежат раздельно и видны каждый.
        /// Сковорода, противень, решётка.</summary>
        Flat = 1,

        /// <summary>Печь: греет то, что внутрь поставили, но содержимое
        /// остаётся собой. Духовка.</summary>
        Oven = 2,

        /// <summary>Держатель: продукт нанизан и виден целиком. Вертел.</summary>
        Holder = 3,

        /// <summary>Хранилище: предметы лежат физически, ничего не происходит.
        /// Ведро, ящик.</summary>
        Storage = 4,

        /// <summary>Мерная: риски на боку, выдаёт ровно столько, сколько набрал.
        /// Банка и рюмка для бетона. Заменяет систему массы.</summary>
        Measure = 5,
    }

    /// <summary>
    /// ОПИСАНИЕ ТАРЫ. Один ассет на тип посуды.
    ///
    /// ═══ ПОЧЕМУ НЕ VesselDef ═══
    ///
    /// В проекте уже есть VesselDef из старой системы готовки. Два типа с одним
    /// именем компилируются (они в разных пространствах имён), но редактор
    /// ищет ассеты по короткому имени и путает их между собой. Пока обе системы
    /// живут рядом, имена обязаны различаться.
    /// </summary>
    [CreateAssetMenu(menuName = "CatCooks/Тара", fileName = "Cookware_")]
    public class CookwareDef : ScriptableObject
    {
        [Header("Что это")]
        public string Title = "Кастрюля";
        public CookwareKind Kind = CookwareKind.Pot;

        [Header("Сколько влезает")]
        [Tooltip("Порций. ГИГАНТИЗМ ЗАДАЁТСЯ ЗДЕСЬ, а не размером продуктов: " +
                 "котёл на сорок порций и есть источник масштаба. Картошку в " +
                 "него опускают краном потому, что её надо сорок штук.")]
        public int Capacity = 20;

        [Header("Что умеет")]
        [Tooltip("Процесс, который тара прикладывает к содержимому, пока включена.\n" +
                 "Кастрюля — варка, казан — тушение, сковорода — жарка, " +
                 "духовка — запекание. None для хранилищ.")]
        public FoodProcess HeatProcess = FoodProcess.Boil;

        [Tooltip("Нужен ли источник огня. Кастрюля без плиты не варит.")]
        public bool NeedsHeatSource = true;

        [Header("Поведение содержимого")]
        [Tooltip("Проглатывает: продукт исчезает как объект и становится частью " +
                 "содержимого. Котёл — да, ведро — нет.")]
        public bool Absorbs = true;

        [Tooltip("Смешивает цвета в один. Котёл — да, сковорода — нет: " +
                 "там куски лежат раздельно и каждый своего цвета.")]
        public bool BlendsColor = true;

        [Header("Мерная тара")]
        [Tooltip("Сколько порций в одной риске. Только для Kind = Measure.")]
        public int PortionPerMark = 1;
    }
}

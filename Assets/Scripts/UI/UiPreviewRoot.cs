using UnityEngine;

/// <summary>
/// МАРКЕР ПРЕВЬЮ-ИЕРАРХИИ. Вешается редакторским инструментом на корень
/// сгенерированного UI.
///
/// Смысл один: при запуске игры вся эта ветка удаляется. Иначе получилось бы
/// два комплекта интерфейса — превью из сцены и настоящий, который скрипты
/// строят в OnStartClient. Наложенные друг на друга канвасы выглядят как
/// «двоится прицел» и ловятся долго.
///
/// Скрипт лежит в обычной папке Scripts, а не в Editor: объект попадает в
/// сцену, и ссылка на компонент должна оставаться валидной и в сборке.
/// </summary>
[DisallowMultipleComponent]
[ExecuteAlways]
public class UiPreviewRoot : MonoBehaviour
{
    [Tooltip("Информационное поле. Эта ветка существует только для правки " +
             "интерфейса в редакторе и удаляется при запуске игры.")]
    [SerializeField, TextArea(2, 4)]
    private string _note =
        "Превью интерфейса. Двигай элементы, потом:\n" +
        "CatCooks → UI → Считать правки обратно.\n" +
        "При запуске игры эта ветка удаляется автоматически.";

    private void Awake()
    {
        if (!Application.isPlaying) return;

        // Игра пошла — превью больше не нужно и только мешает.
        Destroy(gameObject);
    }
}

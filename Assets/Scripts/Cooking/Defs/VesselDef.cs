using UnityEngine;

public enum VesselKind
{
    Pot,      // чан, казан, ковш — варка
    Pan,      // сковорода, лист металла — жарка
    Tray,     // противень, форма — запекание
    Bucket,   // ведро — замес
    Bowl,     // миска — подача
    Mixer     // бетономешалка — вращение
}

/// <summary>
/// Справочник ёмкости.
///
/// SupportedProcesses важнее, чем кажется: сковорода не варит бульон, чан не
/// пассерует. Это прямо из твоего документа — заправка делается ОТДЕЛЬНО на
/// сковороде и только потом идёт в чан. То есть параллельные ёмкости не
/// декорация, а требование рецепта, и проверяется оно одним полем.
/// </summary>
[CreateAssetMenu(menuName = "CatCooks/Vessel", fileName = "Vessel_")]
public class VesselDef : ScriptableObject
{
    [Tooltip("Как называется: «Чан для бетона»")]
    public string DisplayName = "";

    public VesselKind Kind = VesselKind.Pot;

    [Tooltip("Вместимость в ГРАММАХ. Чан на бригаду — тысяч двадцать.")]
    public int CapacityG = 20000;

    [Tooltip("Какие ГРУППЫ обработок эта ёмкость умеет")]
    public ProcessGroup[] SupportedProcesses;

    [Tooltip("ГЛОТАТЬ ПРОДУКТ СРАЗУ ПРИ КАСАНИИ.\n\n" +
             "true (кастрюля, чан) — кинул морковку, она мгновенно стала " +
             "массой во фракции, объект исчез. Правильно для варки: внутри " +
             "супа отдельных морковок нет.\n\n" +
             "false (банка из-под бетона, тазик) — ХРАНИЛИЩЕ. Продукты лежат " +
             "внутри физическими предметами, их видно и можно обрабатывать " +
             "инструментом прямо в таре. Без этого положить картошку в банку " +
             "и раздолбить её невозможно: она растворилась бы в момент " +
             "касания триггера, ещё до первого удара.")]
    public bool AbsorbOnContact = true;

    [Header("Нагрев")]
    public bool CanBeHeated = true;

    [Tooltip("Насколько быстро прогревается содержимое. Чугун медленно, " +
             "тонкий лист металла быстро.")]
    public float HeatTransfer = 1f;
}

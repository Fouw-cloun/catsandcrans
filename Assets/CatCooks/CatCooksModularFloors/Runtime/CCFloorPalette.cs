using System;
using UnityEngine;

namespace CatCooks.Floors
{
    [Serializable]
    public sealed class CCFloorVisual
    {
        [Tooltip("Only MeshFilter + MeshRenderer visuals are copied. Scripts and colliders are not copied.")]
        public GameObject Prefab;
        [Tooltip("Rotate the source before fitting its bounds to a module.")]
        public Vector3 RotationCorrection;
    }

    [CreateAssetMenu(menuName = "CatCooks/Floors/Palette")]
    public sealed class CCFloorPalette : ScriptableObject
    {
        public Material Concrete, Steel, Safety, Rubble;
        [Tooltip("Optional shared atlas material, generated by the construction site builder.")]
        public Material AtlasMaterial;
        public CCFloorVisual Slab = new CCFloorVisual();
        public CCFloorVisual Column = new CCFloorVisual();
        public CCFloorVisual Beam = new CCFloorVisual();
        public CCFloorVisual Visual(CCFloorKind kind)
        {
            switch (kind)
            {
                case CCFloorKind.Slab: return Slab;
                case CCFloorKind.Column: return Column;
                case CCFloorKind.Beam: return Beam;
                default: return null;
            }
        }
        public Material MaterialFor(CCFloorKind kind)
        {
            if (AtlasMaterial != null) return AtlasMaterial;
            switch (kind)
            {
                case CCFloorKind.Slab: case CCFloorKind.Stair: return Concrete;
                case CCFloorKind.Rail: return Safety;
                case CCFloorKind.Debris: return Rubble;
                default: return Steel;
            }
        }
    }
}

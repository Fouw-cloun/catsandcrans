using UnityEngine;

/// <summary>
/// ВОЗМУТИТЕЛЬ ТУМАНА. Вешается на всё, что должно взаимодействовать с
/// туманом или пылью: игрока, котов, технику, а также на неподвижные
/// постройки, вокруг которых воздух чище.
///
/// Компонент ничего не делает сам — он только объявляет себя. Его находит
/// CatCooksVolumeFog и передаёт в симуляцию.
///
/// ═══ ТРИ ВИДА ═══
///
/// ДВИЖУЩИЙСЯ (машина, кот): push и swirl больше нуля. Гонит туман перед
/// собой и оставляет закручивающийся след. Скорость считается автоматически
/// по перемещению трансформа, задавать её не нужно.
///
/// НЕПОДВИЖНЫЙ (постройка, штабель): push и swirl в нуле, carve больше нуля.
/// Просто вытесняет туман из своего объёма.
///
/// ИСТОЧНИК (работающая техника): carve отрицательный — вместо дыры он
/// ДОБАВЛЯЕТ плотность. Так делается пыль от болгарки или отвала, и её не
/// нужно городить отдельной системой частиц.
/// </summary>
[DisallowMultipleComponent]
[AddComponentMenu("CatCooks/Атмосфера/Fog Disturber")]
public class CatCooksFogDisturber : MonoBehaviour
{
    [Tooltip("Радиус влияния в метрах. Не размер модели, а размер зоны, " +
             "которую объект расчищает или мутит.")]
    [Min(0.05f)] public float radius = 1.8f;

    [Header("Движение")]
    [Tooltip("РАСТАЛКИВАНИЕ. Насколько сильно объект гонит туман перед собой " +
             "при движении. У стоящего объекта не работает вообще.")]
    [Range(0f, 12f)] public float push = 4f;

    [Tooltip("ЗАКРУЧИВАНИЕ. Вихри в следе. Без него за машиной остаётся " +
             "просто коридор, а с ним — расходящиеся завихрения.\n\n" +
             "Это самая заметная часть эффекта: именно по вихрям видно, что " +
             "туман живой, а не нарисованный.")]
    [Range(0f, 8f)] public float swirl = 1.6f;

    [Header("Плотность")]
    [Tooltip("ВЫТЕСНЕНИЕ.\n\n" +
             "Больше нуля — объект выедает дыру в тумане.\n" +
             "Ноль — не трогает плотность, только двигает.\n" +
             "МЕНЬШЕ НУЛЯ — наоборот ДОБАВЛЯЕТ пыль. Так делается работающая " +
             "техника: болгарка, отвал, сыплющийся с ковша грунт.")]
    [Range(-1f, 1f)] public float carve = 0.9f;

    [Tooltip("Отключить, не снимая компонент. Удобно для техники, которая " +
             "пылит только когда работает.")]
    public bool active = true;

    [Tooltip("Общий множитель силы. Крути его из кода: пыль из-под колеса " +
             "должна зависеть от скорости машины.")]
    [Range(0f, 2f)] public float strength = 1f;

    /// <summary>Позиция прошлого кадра — из неё симуляция считает скорость.</summary>
    [System.NonSerialized] public Vector3 previousPosition;

    [System.NonSerialized] public bool initialized;

    private void OnEnable()
    {
        previousPosition = transform.position;
        initialized = true;
    }

    private void OnDrawGizmosSelected()
    {
        Gizmos.color = carve >= 0f
            ? new Color(0.5f, 0.9f, 1f, 0.8f)      // расчищает
            : new Color(1f, 0.7f, 0.35f, 0.8f);    // добавляет пыль

        Gizmos.DrawWireSphere(transform.position, radius);
    }
}
